# A string is a sequence of characters enclosed in quotes.
# String = Text/Data inside quotes

name = "Maya"

nameshort = name[0:2]        #it shows the output from index 0 to 1  

print(nameshort)        #start from index 0 all the way till 2 (excluding 2)
character1 = name[1]
print(character1)
print(name[:3])             #prints characters from index 0 to 2
print(name[0:])             #print from 0 to end of the string
print(name[0:3])
print(name[-4:-1])


